print(b)

"""## 7. Augmented Matrix

For Gaussian Elimination, the coefficient matrix A and the constant vector B are combined to form the augmented matrix:

[A | B]

The augmented matrix contains all the information required to perform the row operations.
"""

# Create the augmented matrix [A | B]
augmented = np.column_stack((A, b))
print("Augmented Matrix [A | B]:")
print(augmented)

"""## 8. Gaussian Elimination

Gaussian Elimination is a direct method for solving a system of linear equations.

It consists mainly of two stages:

### Stage 1: Forward Elimination

The elements below the main diagonal are eliminated so that the coefficient matrix becomes an upper triangular matrix.

### Stage 2: Backward Substitution

Starting from the last equation, the unknown variables are calculated in reverse order.

For our system, the augmented matrix is transformed as follows:

Initial matrix:

[ 3  2  1 | 19 ]
[ 2  3  1 | 22 ]
[ 1  1  2 | 13 ]

After forward elimination:

[ 3  2  1 | 19 ]
[ 0  5  1 | 28 ]
[ 0  0 24 | 72 ]

The resulting upper triangular system can then be solved using backward substitution.
"""

def gaussian_elimination(A, b):

    # Create a copy so that the original matrices are not changed
    augmented = np.column_stack((A, b)).astype(float)

    n = len(b)

    print("Initial Augmented Matrix:")
    print(augmented)

    # -----------------------------------------
    # Forward Elimination
    # -----------------------------------------

    for i in range(n):

        # Check whether pivot is zero
        if augmented[i][i] == 0:
            raise ValueError("Zero pivot encountered.")

        # Eliminate elements below the pivot
        for j in range(i + 1, n):

            factor = augmented[j][i] / augmented[i][i]

            augmented[j] = augmented[j] - factor * augmented[i]

        print("\nAfter eliminating column", i + 1)
        print(augmented)

    # -----------------------------------------
    # Backward Substitution
    # -----------------------------------------

    x = np.zeros(n)

    for i in range(n - 1, -1, -1):

        sum_value = 0

        for j in range(i + 1, n):
            sum_value += augmented[i][j] * x[j]

        x[i] = (augmented[i][n] - sum_value) / augmented[i][i]

    return x

# Solve the system using our Gaussian Elimination function

solution = gaussian_elimination(A, b)

print("\nFinal Solution:")
